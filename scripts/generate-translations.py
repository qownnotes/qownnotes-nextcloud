"""Generate Nextcloud's browser and PHP catalogs from translations/ui.tsv."""

import argparse
import ast
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Same gettext plural rules used by Nextcloud's translation tooling.
PLURAL_FORMS = {
    "de": "nplurals=2; plural=(n != 1);",
    "zh_CN": "nplurals=1; plural=0;",
    "ru": "nplurals=4; plural=(n%10==1 && n%100!=11 ? 0 : n%10>=2 && n%10<=4 && (n%100<12 || n%100>14) ? 1 : n%10==0 || (n%10>=5 && n%10<=9) || (n%100>=11 && n%100<=14)? 2 : 3);",
    "it": "nplurals=3; plural=n == 1 ? 0 : n != 0 && n % 1000000 == 0 ? 1 : 2;",
    "pt_BR": "nplurals=3; plural=(n == 0 || n == 1) ? 0 : n != 0 && n % 1000000 == 0 ? 1 : 2;",
    "pl": "nplurals=4; plural=(n==1 ? 0 : (n%10>=2 && n%10<=4) && (n%100<12 || n%100>14) ? 1 : n!=1 && (n%10>=0 && n%10<=1) || (n%10>=5 && n%10<=9) || (n%100>=12 && n%100<=14) ? 2 : 3);",
    "fr": "nplurals=3; plural=(n == 0 || n == 1) ? 0 : n != 0 && n % 1000000 == 0 ? 1 : 2;",
    "es": "nplurals=3; plural=n == 1 ? 0 : n != 0 && n % 1000000 == 0 ? 1 : 2;",
}
LITERAL = r"'((?:\\.|[^'\\])*)'"
SINGULAR_CALL = re.compile(r"(?:\bt\(\s*'qownnotes'\s*,\s*|->t\(\s*)" + LITERAL)
PLURAL_CALL = re.compile(
    r"\bn\(\s*'qownnotes'\s*,\s*" + LITERAL + r"\s*,\s*" + LITERAL
)
PLACEHOLDER = re.compile(r"\{\w+\}|%n|%(?:\d+\$)?[sd]")


def source_strings(root):
    """Extract literal t()/n() calls in our JS, Vue, PHP and templates."""
    strings = set()
    for folder in ("src", "lib", "templates"):
        for path in (root / folder).rglob("*"):
            if path.suffix not in (".js", ".vue", ".php"):
                continue
            text = path.read_text(encoding="utf-8")
            for match in SINGULAR_CALL.finditer(text):
                strings.add(ast.literal_eval("'" + match[1] + "'"))
            for match in PLURAL_CALL.finditer(text):
                singular, plural = (
                    ast.literal_eval("'" + value + "'") for value in match.groups()
                )
                strings.add(f"_{singular}_::_{plural}_")
    return strings


def load_translations(path):
    """Validate all languages, plural forms and substitution placeholders."""
    catalogs = {language: {} for language in PLURAL_FORMS}
    with path.open(encoding="utf-8", newline="") as stream:
        rows = csv.reader(stream, delimiter="\t", quoting=csv.QUOTE_NONE)
        if next(rows) != ["en", *PLURAL_FORMS]:
            raise ValueError("Unexpected translation columns")
        for line, row in enumerate(rows, start=2):
            if len(row) != len(catalogs) + 1:
                raise ValueError(f"Line {line}: unexpected number of columns")
            source, *values = row
            if not source or source in catalogs["de"]:
                raise ValueError(f"Line {line}: empty or duplicate source string")
            plural = source.startswith("_") and "_::_" in source
            placeholders = set(PLACEHOLDER.findall(source))
            for language, value in zip(catalogs, values):
                forms = value.split("|") if plural else [value]
                expected = int(re.search(r"nplurals=(\d+)", PLURAL_FORMS[language])[1])
                if len(forms) != (expected if plural else 1):
                    raise ValueError(f"Line {line}, {language}: wrong plural form count")
                if any(not form.strip() for form in forms):
                    raise ValueError(f"Line {line}, {language}: empty translation")
                if any(set(PLACEHOLDER.findall(form)) != placeholders for form in forms):
                    raise ValueError(f"Line {line}, {language}: placeholders differ")
                catalogs[language][source] = forms if plural else value
    return catalogs


def generated_files(root=ROOT):
    catalogs = load_translations(root / "translations/ui.tsv")
    actual = set(catalogs["de"])
    expected = source_strings(root)
    if actual != expected:
        raise ValueError(
            f"Translation coverage mismatch: missing={sorted(expected - actual)}, "
            f"obsolete={sorted(actual - expected)}"
        )
    files = {}
    for language, translations in catalogs.items():
        translations = dict(sorted(translations.items()))
        plural_form = PLURAL_FORMS[language]
        files[f"{language}.json"] = json.dumps(
            {"translations": translations, "pluralForm": plural_form},
            ensure_ascii=False,
            indent=4,
        ) + "\n"
        files[f"{language}.js"] = (
            "// Generated by scripts/generate-translations.py; do not edit.\n"
            'OC.L10N.register(\n    "qownnotes",\n'
            + json.dumps(translations, ensure_ascii=False, indent=4)
            + ",\n    "
            + json.dumps(plural_form)
            + "\n);\n"
        )
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing files")
    args = parser.parse_args()
    try:
        files = generated_files()
        output = ROOT / "l10n"
        if args.check:
            for name, content in files.items():
                path = output / name
                if not path.is_file() or path.read_text(encoding="utf-8") != content:
                    raise ValueError(f"{path}: regenerate translation catalogs")
        else:
            output.mkdir(exist_ok=True)
            for name, content in files.items():
                (output / name).write_text(content, encoding="utf-8")
    except ValueError as error:
        parser.exit(1, f"{error}\n")
    print(f"{'Checked' if args.check else 'Generated'} {len(files)} translation catalogs")


if __name__ == "__main__":
    main()
